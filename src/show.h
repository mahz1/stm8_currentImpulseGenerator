#ifndef SHOW_HEADER_GUARD
#define SHOW_HEADER_GUARD

#include "common.h"

// ============================================================
//  Тип ответа пользователя (используется во всех функциях ввода)
// ============================================================
typedef enum {
    ANSWER_ENTER,   // Нажата клавиша '#'
    ANSWER_ESC      // Нажата клавиша '*'
} ANSWER_TYPE;

// ============================================================
//  Инициализация LCD и внутренних переменных
// ============================================================
void show_init(void);

// ============================================================
//  Вывод строки с перекодировкой UTF-8 → знакогенератор LCD
//  col — позиция по X (0..15)
//  row — строка (0 или 1)
//  str — указатель на строку (UTF-8)
// ============================================================
void show_send_string(BYTE col, BYTE row, const char* str);

// ============================================================
//  Ожидание нажатия клавиши '#'
//  Возврат: ANSWER_ENTER или ANSWER_ESC
// ============================================================
ANSWER_TYPE show_wait_command(void);

// ============================================================
//  Режим заряда: показывает проценты заряда и напряжение,
//  управляет ключами через charge_*
//  Возврат: ANSWER_ENTER или ANSWER_ESC
// ============================================================
ANSWER_TYPE show_charging(WORD amperage);

// ============================================================
//  Ввод длительности импульса (в целых мс с десятыми)
// ============================================================
ANSWER_TYPE show_input_length(WORD* len);

// ============================================================
//  Ввод значения тока (в Амперах)
// ============================================================
ANSWER_TYPE show_input_amperage(WORD* amperage);

// ============================================================
//  Главное меню: выбор режима (Генерация / Разряд / Set Ki)
// ============================================================
MODE_TYPE show_get_mode(void);

// ============================================================
//  Показать результат измерения (ток и длительность импульса)
// ============================================================
void show_result(WORD amperage);

// ============================================================
//  Ввод тока, измеренного образцовым прибором (для калибровки)
// ============================================================
ANSWER_TYPE show_get_prec_amperage(WORD* value);

// ============================================================
//  Режим разряда с отображением напряжения
// ============================================================
void show_discharge(void);

// ============================================================
//  Аварийный режим: разряд + мигающее сообщение «Тревога»
// ============================================================
void show_emergency(void);

// ============================================================
//  Отладочный вывод (для проверки параметров импульса)
// ============================================================
ANSWER_TYPE show_debug(WORD amperage);
ANSWER_TYPE show_debug2(void);

// ============================================================
//  Ввод Ki (калибровочного коэффициента)
// ============================================================
ANSWER_TYPE show_set_ki(void);

void show_set_addr(unsigned char addr);

void show_send_cmd_byte(unsigned char c);
void show_send_data_byte(unsigned char c);

void show_clear(void);

#endif  // SHOW_HEADER_GUARD