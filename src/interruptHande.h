#ifndef INTERRUPT_HANDLE_HEADER_GUARD
#define INTERRUPT_HANDLE_HEADER_GUARD

// ============================================================
//  Обработчики прерываний STM8
// ============================================================
//  Реализация находится в interruptHande.c
//  Для каждого периферийного устройства с прерыванием здесь
//  описан соответствующий INTERRUPT_HANDLER.
//
//  На данный момент реализован только TIM1 Update/Overflow —
//  он выключает импульс по окончании заданной длительности.
// ============================================================

// Прототипов «обычных» функций здесь нет, потому что
// обработчики прерываний регистрируются компилятором
// через макрос INTERRUPT_HANDLER в interruptHande.c.

#endif  // INTERRUPT_HANDLE_HEADER_GUARD